"""Ports for shared infrastructure provided by outbound adapters."""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable


@runtime_checkable
class LoggerPort(Protocol):
    def info(self, msg: str, tag: Any = None) -> None: ...
    def debug(self, msg: str, tag: Any = None) -> None: ...
    def warning(self, msg: str, tag: Any = None) -> None: ...
    def error(self, msg: str, tag: Any = None) -> None: ...
    def log(self) -> Any: ...
    def add_log_buffer(self, msg: str, tag: Any = None) -> None: ...
    def get_buffer_str(self) -> list[str]: ...
    def get_level(self) -> str: ...
    def setLevel(self, level: Any) -> None: ...


@runtime_checkable
class StatisticsTableRenderer(Protocol):
    def __call__(self, stats: list[Any]) -> str: ...
